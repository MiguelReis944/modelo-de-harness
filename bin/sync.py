#!/usr/bin/env python3
"""Project the canonical harness into Claude Code and Codex (Python 3.10+)."""
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

MARKER = '# Generated by harness sync; edit canonical sources instead.\n'


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8', newline='\n') as stream:
        stream.write(text)


def config_list(root, key):
    return subprocess.check_output(
        [sys.executable, str(root / 'bin/yaml_list.py'), key,
         str(root / 'harness.config.yaml')], encoding='utf-8').splitlines()


def codex_mcp(servers):
    lines = [MARKER.rstrip()]
    for name, server in servers.items():
        if not server.get('enabled', False):
            continue
        section = 'mcp_servers.' + json.dumps(name, ensure_ascii=False)
        lines.append('\n[' + section + ']')
        transport = server.get('transport', 'stdio')
        if transport == 'stdio':
            lines.append('command = ' + json.dumps(server['command'], ensure_ascii=False))
            lines.append('args = ' + json.dumps(server.get('args', []), ensure_ascii=False))
            env, forwarded = {}, []
            for key, value in server.get('env', {}).items():
                if value == '${' + key + '}':
                    forwarded.append(key)
                elif '${' in value:
                    raise ValueError('Codex requires same-name env references: ' + key)
                else:
                    env[key] = value
            if forwarded:
                lines.append('env_vars = ' + json.dumps(forwarded))
            if env:
                lines.append('[' + section + '.env]')
                lines.extend(json.dumps(k) + ' = ' + json.dumps(v, ensure_ascii=False)
                             for k, v in env.items())
        elif transport in ('http', 'streamable-http'):
            lines.append('url = ' + json.dumps(server['url'], ensure_ascii=False))
        else:
            raise ValueError('Unsupported transport: ' + transport)
    return '\n'.join(lines) + '\n'


def sync(root):
    root = root.resolve()
    selected = config_list(root, 'tools') or ['claude']
    if set(selected) - {'claude', 'codex'}:
        raise ValueError('tools must contain only claude and/or codex')
    skills = config_list(root, 'active_skills')
    agents = config_list(root, 'active_agents')
    for name in skills + agents:
        if not re.fullmatch(r'[A-Za-z0-9_-]+', name):
            raise ValueError('Invalid skill/agent name: ' + name)
    for name in skills:
        if not (root / 'catalog/skills' / name / 'SKILL.md').is_file():
            raise ValueError('Missing skill: ' + name)
    bodies = {name: (root / 'agents' / name / 'AGENT.md').read_text(encoding='utf-8')
              for name in agents}
    servers = json.loads((root / 'mcp/servers.json').read_text(encoding='utf-8'))['servers']
    rendered = codex_mcp(servers) if 'codex' in selected else ''
    config = root / '.codex/config.toml'
    if 'codex' in selected and config.exists() and not config.read_text(encoding='utf-8').startswith(MARKER):
        raise ValueError('Existing .codex/config.toml is not generated; merge it manually before sync')
    # Check all destination ancestors before any write or recursive removal.
    for folder in ('.claude', '.claude/skills', '.claude/agents', '.agents', '.agents/skills', '.codex', '.codex/agents', '.codex/config.toml', '.claude/settings.json', 'CLAUDE.md', '.mcp.json'):
        target = root / folder
        if target.is_symlink() or not target.resolve().is_relative_to(root):
            raise ValueError('Unsafe generated destination: ' + str(target))
    for tool in selected:
        skill_dir = root / ('.claude/skills' if tool == 'claude' else '.agents/skills')
        # These directories are generated in full; stale skills must disappear.
        if skill_dir.exists():
            shutil.rmtree(skill_dir)
        skill_dir.mkdir(parents=True)
        for name in skills:
            shutil.copytree(root / 'catalog/skills' / name, skill_dir / name)
        agent_dir = root / ('.claude/agents' if tool == 'claude' else '.codex/agents')
        if agent_dir.exists():
            shutil.rmtree(agent_dir)
        agent_dir.mkdir(parents=True)
        for name, body in bodies.items():
            description = 'Perfil ' + name + ' do harness; siga as instrucoes deste agente.'
            if tool == 'claude':
                write(agent_dir / (name + '.md'), '---\nname: ' + name + '\ndescription: ' + description + '\n---\n\n' + body)
            else:
                text = MARKER + 'name = ' + json.dumps(name) + '\ndescription = ' + json.dumps(description) + '\ndeveloper_instructions = ' + json.dumps(body, ensure_ascii=False) + '\n'
                write(agent_dir / (name + '.toml'), text)
        if tool == 'claude':
            shutil.copyfile(root / 'AGENTS.md', root / 'CLAUDE.md')
            output = subprocess.check_output([sys.executable, str(root / 'bin/render_mcp.py'), str(root / 'mcp/servers.json')], encoding='utf-8')
            write(root / '.mcp.json', output)
            subprocess.run([sys.executable, str(root / 'bin/render_settings.py'), str(root / 'hooks/hooks.json'), str(root / '.claude/settings.json')], check=True)
        else:
            write(config, rendered)
        print(tool + ': ' + str(len(skills)) + ' skills, ' + str(len(agents)) + ' agents; MCP configured')


if __name__ == '__main__':
    try:
        sync(Path(__file__).resolve().parent.parent)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        sys.exit(str(error))
